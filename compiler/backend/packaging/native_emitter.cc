/// The directory holding this executable, asked of the OS (a bare or
/// PATH-found argv[0] says nothing about where the binary is), with
/// symlinks resolved; argv[0]'s directory, then ".", when the OS cannot say.
std::string ExecutableDir(const char* argv0) {
  std::string exe;
#if defined(__APPLE__)
  uint32_t n = 0;
  _NSGetExecutablePath(nullptr, &n);
  if (n > 0) {
    std::string buf(n, '\0');
    if (_NSGetExecutablePath(buf.data(), &n) == 0) exe.assign(buf.c_str());
  }
#elif defined(__linux__)
  char buf[PATH_MAX];
  const ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
  if (n > 0) exe.assign(buf, static_cast<size_t>(n));
#endif
  if (exe.empty() && argv0 && *argv0) exe = argv0;
#if defined(__unix__) || defined(__APPLE__)
  if (!exe.empty()) {
    char real[PATH_MAX];
    if (realpath(exe.c_str(), real)) exe = real;
  }
#endif
  const size_t slash = exe.find_last_of("/\\");
  if (slash == std::string::npos) return ".";
  if (slash == 0) return "/";
  return exe.substr(0, slash);
}

const char* Arg(int argc, char** argv, const char* flag, const char* dflt) {
  for (int i = 1; i + 1 < argc; ++i)
    if (std::strcmp(argv[i], flag) == 0) return argv[i + 1];
  return dflt;
}

bool Has(int argc, char** argv, const char* flag) {
  for (int i = 1; i < argc; ++i)
    if (std::strcmp(argv[i], flag) == 0) return true;
  return false;
}

// Digits only (S4 #150, review F63): strtoull skips leading whitespace and
// negates a "-1" behind it, which is how `--steps " -1"` parsed.
bool ParseU64(const char* s, uint64_t* out) {
  return seeml::update::recipe::ParseU64Strict(s, out);
}

// A finite decimal, consumed completely (S4 #150): strtod skips leading
// whitespace and takes hex floats, "nan" and "inf".
bool ParseF64(const char* s, double* out) {
  return seeml::update::recipe::ParseF64Strict(s, out);
}

