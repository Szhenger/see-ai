std::expected<void, std::string> WriteFile(const std::string& path,
                                           const std::string& content,
                                           bool executable = false) {
  std::ofstream f(path, std::ios::binary | std::ios::trunc);
  if (!f)
    return generating::FileError(generating::kNativeEmitter, "cannot write",
                                 path);
  f << content;
  // Close before the state check: with contents this small the whole file
  // can sit in the stream buffer, so a failed flush-at-close is the only
  // signal a truncated package would ever give.
  f.close();
  if (f.fail())
    return generating::FileError(generating::kNativeEmitter, "short write to",
                                 path);
  if (executable) {
    std::error_code ec;
    std::filesystem::permissions(path,
                                 std::filesystem::perms::owner_all |
                                     std::filesystem::perms::group_read |
                                     std::filesystem::perms::group_exec |
                                     std::filesystem::perms::others_read |
                                     std::filesystem::perms::others_exec,
                                 ec);
  }
  return {};
}

// Writes the plan as a decimal byte-array translation unit, streamed (E2,
// #81): the rendered text is ~4x the plan, and building it as per-chunk
// strings, concatenating them into one more string and only then writing
// held ~9x the plan resident at the peak. Here a bounded window of chunks
// renders in parallel, is written, and is reused — the peak is the plan
// plus a constant — and the file is character-identical to the old one.
//
// Manual decimal emission: a snprintf call per byte dominates emission
// time once plans reach megabytes (frozen weights live in the blob).
// Three digit appends and a comma beat the formatter by an order of
// magnitude and need no format-string parsing. Each byte's text (and its
// line break, keyed off the GLOBAL index) is independent of every other
// byte, so fixed chunks render in parallel and concatenate in order.
std::expected<void, std::string> WriteEmbeddedTU(
    const std::string& path, const std::vector<uint8_t>& plan) {
  std::ofstream f(path, std::ios::binary | std::ios::trunc);
  if (!f)
    return generating::FileError(generating::kNativeEmitter, "cannot write",
                                 path);
  f << "// Generated by seeml-update-compile. The compiled Update Plan as an\n"
       "// object-file byte array: instruction streams, memory layout, frozen\n"
       "// weights, and adapter initialization — the entire update, as data.\n"
       "#include <cstddef>\n\n"
       "extern const unsigned char kSeemlUpdatePlan[] "
       "__attribute__((aligned(64)));\n"
       "extern const size_t kSeemlUpdatePlanSize;\n\n"
       "const unsigned char kSeemlUpdatePlan[] __attribute__((aligned(64))) = "
       "{\n";
  constexpr size_t kEmbedGrain = 256 * 1024;  // plan bytes per chunk
  constexpr size_t kWindowChunks = 64;        // 16 MiB of plan per window
  std::vector<std::string> parts(kWindowChunks);
  for (std::string& part : parts) part.reserve(kEmbedGrain * 4 + 8);
  for (size_t base = 0; base < plan.size();
       base += kEmbedGrain * kWindowChunks) {
    const size_t window =
        std::min(plan.size() - base, kEmbedGrain * kWindowChunks);
    const size_t chunks = (window + kEmbedGrain - 1) / kEmbedGrain;
    // One ParallelFor item per chunk: the window's geometry is explicit,
    // never the pool's.
    ParallelFor(chunks, 1, [&](size_t c0, size_t c1, size_t) {
      for (size_t c = c0; c < c1; ++c) {
        std::string& out = parts[c];
        out.clear();
        const size_t begin = base + c * kEmbedGrain;
        const size_t end = std::min(begin + kEmbedGrain, base + window);
        for (size_t i = begin; i < end; ++i) {
          const unsigned v = plan[i];
          if (v >= 100) {
            out += static_cast<char>('0' + v / 100);
            out += static_cast<char>('0' + (v / 10) % 10);
            out += static_cast<char>('0' + v % 10);
          } else if (v >= 10) {
            out += static_cast<char>('0' + v / 10);
            out += static_cast<char>('0' + v % 10);
          } else {
            out += static_cast<char>('0' + v);
          }
          out += ',';
          if ((i + 1) % 24 == 0) out += '\n';
        }
      }
    });
    for (size_t c = 0; c < chunks; ++c)
      f.write(parts[c].data(), static_cast<std::streamsize>(parts[c].size()));
  }
  f << "\n};\nconst size_t kSeemlUpdatePlanSize = sizeof(kSeemlUpdatePlan);\n";
  f.close();
  if (f.fail())
    return generating::FileError(generating::kNativeEmitter, "short write to",
                                 path);
  return {};
}

