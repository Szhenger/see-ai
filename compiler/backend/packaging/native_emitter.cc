/// The certificate gate of a relaxed plan's script: no certificate, no
/// build, and the seal of the plan it was checked for compiled into the
/// runner.
void AppendCertificateGate(std::string& s) {
  // "No certificate, no relaxed plan" (P3), enforced where the binary
  // is made and not only where tool/pack_update.py makes it
  // (2026-09-24 review, N17) — and, since F2 #206, carried into the
  // binary: the gate that passes compiles the plan's seal into the
  // runner (SEEML_CERTIFIED_PLAN_HASH), and the runner refuses every
  // other relaxed plan at load.
  //
  // The gate is the attestation, not the JSON. This script runs on the
  // device with POSIX sh and no parser, and the two greps it used to be
  // were satisfied by a refused document with a nested "granted". So
  // tool/certify_numerics.py writes, beside a certificate the full check
  // passed, one fixed line naming the plan's SHA-256, the plan's seal
  // and the certificate file's SHA-256; the script recomputes the line
  // from the three files' bytes and requires the attestation to be
  // exactly it. Any other certificate file — a refusal, an edit, a
  // nested document — has another SHA-256 and does not build.
  s += "# This plan carries relaxed instructions (--precision "
       "certified-bf16,\n";
  s += "# plan v18): it is built only beside the numerics certificate "
       "that\n";
  s += "# tool/certify_numerics.py granted for exactly these plan bytes, "
       "and\n";
  s += "# the binary it builds runs no other relaxed plan (F2 #206).\n";
  s += "if [ ! -f numerics_certificate.json ]; then\n";
  s +=
      "  echo \"build.sh: update_plan.seeu carries relaxed GEMMs and this\" \\\n";
  s += "       \"package has no numerics_certificate.json; run\" \\\n";
  s +=
      "       \"tool/certify_numerics.py certify <pkg> --corpus <corpus.sds>\" \\\n";
  s +=
      "       \"[--source <model.smf>], then tool/pack_update.py <pkg> --build\" >&2\n";
  s += "  exit 1\n";
  s += "fi\n";
  s += "if [ ! -f numerics_certificate.attest ]; then\n";
  s += "  echo \"build.sh: this package has no numerics_certificate.attest "
       "— the\" \\\n";
  s += "       \"attestation tool/certify_numerics.py writes beside a "
       "GRANTED\" \\\n";
  s += "       \"certificate (a refused one has none): re-run certify, or\" "
       "\\\n";
  s += "       \"tool/pack_update.py <pkg>, which re-checks the "
       "certificate in full\" >&2\n";
  s += "  exit 1\n";
  s += "fi\n";
  s += "if command -v shasum >/dev/null 2>&1; then\n";
  s += "  PLAN_SHA=$(shasum -a 256 update_plan.seeu | cut -d' ' -f1)\n";
  s += "  CERT_SHA=$(shasum -a 256 numerics_certificate.json | cut -d' ' "
       "-f1)\n";
  s += "else\n";
  s += "  PLAN_SHA=$(sha256sum update_plan.seeu | cut -d' ' -f1)\n";
  s += "  CERT_SHA=$(sha256sum numerics_certificate.json | cut -d' ' "
       "-f1)\n";
  s += "fi\n";
  // The seal: PlanHeader::plan_hash, eight bytes little-endian. Read a
  // byte at a time and reversed here, so the host's own byte order never
  // enters; the offset is the header's, taken from the struct this
  // compiler was built with.
  s += "# The plan's seal (PlanHeader::plan_hash): 8 bytes little-endian "
       "at\n";
  s += "# offset " + std::to_string(offsetof(PlanHeader, plan_hash)) +
       " of the plan file.\n";
  s += "set -- $(dd if=update_plan.seeu bs=1 skip=" +
       std::to_string(offsetof(PlanHeader, plan_hash)) +
       " count=8 2>/dev/null | od -An -tx1)\n";
  s += "if [ $# -ne 8 ]; then\n";
  s += "  echo \"build.sh: update_plan.seeu is too short to carry a plan "
       "seal\" >&2\n";
  s += "  exit 1\n";
  s += "fi\n";
  s += "PLAN_SEAL=\"$8$7$6$5$4$3$2$1\"\n";
  s += "ATTESTATION=\"seeml-numerics-certificate v1 granted "
       "plan-sha256=$PLAN_SHA plan-seal=$PLAN_SEAL "
       "certificate-sha256=$CERT_SHA\"\n";
  s += "if [ \"$(cat numerics_certificate.attest)\" != \"$ATTESTATION\" ]; "
       "then\n";
  s += "  echo \"build.sh: numerics_certificate.attest does not attest "
       "this\" \\\n";
  s += "       \"certificate for this plan: it was written for other plan "
       "bytes\" \\\n";
  s += "       \"(SHA-256 or seal mismatch: re-certify after recompiling) "
       "or for\" \\\n";
  s += "       \"another numerics_certificate.json (one edited or replaced "
       "since it\" \\\n";
  s += "       \"was granted is not a granted certificate)\" >&2\n";
  s += "  exit 1\n";
  s += "fi\n";
  s += "# The gate passed: this binary may run this relaxed plan, and no "
       "other.\n";
  s += "CERT_FLAGS=\"-DSEEML_CERTIFIED_PLAN_HASH=0x${PLAN_SEAL}ull\"\n";
}

/// The compile flags: the tile hook, and Accelerate for a relaxed plan.
void AppendCompileFlags(std::string& s, bool relaxed_plan) {
  s += "# The CPU GEMM tile geometry travels IN THE PLAN (header v11): the\n";
  s += "# compiler decided it from a measured kernel-policy table or left\n";
  s += "# the runtime's defaults. It is a throughput knob only — results\n";
  s += "# are bit-identical for any tiling the kernel accepts. This hook\n";
  s += "# changes the compiled-in default a zero header field selects:\n";
  s +=
      "#   SEEML_TILE_FLAGS=\"-DSEEML_GEMM_TILE_K=64 -DSEEML_GEMM_TILE_N=256\"\n";
  s += "TILE_FLAGS=\"${SEEML_TILE_FLAGS-}\"\n";
  s += "# -pthread: the runtime parallelizes its kernels and pipelines the\n";
  s += "# batch feeder; SEEML_THREADS=1 at run time restores fully serial\n";
  s += "# execution (with bit-identical results — chunking is fixed).\n";
  s += "FLAGS=\"-std=c++23 -O2 -Wall -Wextra -pthread -I. $TILE_FLAGS\"\n";
  // Relaxed plans (v18): the CPU backend may run the frozen-weight f32
  // GEMMs on Accelerate — the AMX / SME matrix units — on Apple hosts. An
  // exact plan's script never mentions the framework, so the zero-
  // dependency promise holds by default and the exception is visible.
  s += "ACCEL_FLAGS=\"\"\n";
  s += "ACCEL_LDFLAGS=\"\"\n";
  if (relaxed_plan) {
    s +=
        "# This plan carries relaxed GEMMs (--precision certified-bf16, plan\n";
    s +=
        "# v18, certified at packaging): on Apple hosts the CPU backend runs\n";
    s +=
        "# their f32- and int8-weight forms on Accelerate's SGEMM (the AMX /\n";
    s += "# SME matrix units; an int8 weight is widened panel by panel).\n";
    s += "# SEEML_NO_ACCELERATE=1 keeps every kernel portable.\n";
    s +=
        "if [ \"$(uname -s)\" = \"Darwin\" ] && [ -z \"${SEEML_NO_ACCELERATE:-}\" ]; then\n";
    s += "  ACCEL_FLAGS=\"-DSEEML_ACCELERATE\"\n";
    s += "  ACCEL_LDFLAGS=\"-framework Accelerate\"\n";
    s += "fi\n";
  }
  s += "FLAGS=\"$FLAGS $ACCEL_FLAGS\"\n";
}

/// The translation unit the plan reaches the binary through.
void AppendPlanUnit(std::string& s) {
  s += "# The plan reaches the binary through one of two translation units:\n";
  s +=
      "# update_plan_embedded.S, the .incbin stub tool/pack_update.py writes\n";
  s +=
      "# (page-aligned, assembles in seconds at any plan size; it needs only\n";
  s += "# the preprocessor and assembler, so it takes no C++ flags), or the\n";
  s += "# compiler's default decimal byte-array update_plan_embedded.cc —\n";
  s +=
      "# or through neither (#158): a package with no embedded TU builds the\n";
  s += "# disk mode, whose binary maps update_plan.seeu beside itself (or\n";
  s += "# --plan FILE) at start-up and validates it exactly as an embedded\n";
  s += "# plan. That is the form for plans the linker and the loader cannot\n";
  s +=
      "# carry (above ~1.8 GB on macOS arm64: ld segfaults, then dyld cannot\n";
  s += "# map the image under the shared cache); tool/pack_update.py chooses\n";
  s += "# it by plan size. The two symbols still resolve: an empty plan.\n";
  s += "PLAN_NOTE=\"\"\n";
  s += "if [ -f update_plan_embedded.S ]; then\n";
  s += "  $CXX -c update_plan_embedded.S -o update_plan_embedded.o\n";
  s += "elif [ -f update_plan_embedded.cc ]; then\n";
  s += "  $CXX $FLAGS -c update_plan_embedded.cc -o update_plan_embedded.o\n";
  s += "else\n";
  s += "  printf '%s\\n' '#include <cstddef>' \\\n";
  s += "    'extern const unsigned char kSeemlUpdatePlan[]; "
       "extern const size_t kSeemlUpdatePlanSize;' \\\n";
  s += "    'const unsigned char kSeemlUpdatePlan[1] = {0}; "
       "const size_t kSeemlUpdatePlanSize = 0;' > update_plan_none.cc\n";
  s += "  $CXX $FLAGS -c update_plan_none.cc -o update_plan_embedded.o\n";
  s += "  rm -f update_plan_none.cc\n";
  s += "  PLAN_NOTE=\" (no embedded plan: ship update_plan.seeu beside it)\"\n";
  s += "fi\n";
}

/// The runner and the vendored runtime, one object each.
void AppendRuntimeUnits(std::string& s, bool relaxed_plan) {
  // The certified seal reaches the one unit that loads the plan. An exact
  // plan's script never mentions it: its runner is built with no relaxed
  // permit, and its build.sh is byte for byte what it was before F2 #206.
  s += relaxed_plan
           ? "$CXX $FLAGS $CERT_FLAGS -c update_main.cc -o update_main.o\n"
           : "$CXX $FLAGS -c update_main.cc -o update_main.o\n";
  s += "$CXX $FLAGS -c source/parallel/parallel_for.cc -o parallel_for.o\n";
  s +=
      "$CXX $FLAGS -c source/tokenizer/byte_level_bpe.cc -o byte_level_bpe.o\n";
  s += "$CXX $FLAGS -c source/tokenizer/text_ingest.cc -o text_ingest.o\n";
  s +=
      "for unit in executor/gemm executor/elementwise executor/activation "
      "executor/normalization executor/loss executor/optimizer "
      "executor/attention executor/backend executor/cpu_backend "
      "pipeline/dataset pipeline/batch_pipeline verifier/plan_validator "
      "storage/durable_io storage/checkpoint loader/contract loader/plan_loader gating/gate profiler/runtime_screen "
      "dispatcher/update_engine; do\n";
  s += "  $CXX $FLAGS -c \"runtime/$unit.cc\" -o \"$(basename $unit).o\"\n";
  s += "done\n";
}

/// What the target decides: the Metal backend or its stub, and the
/// energy meter's framework.
void AppendPlatformUnits(std::string& s) {
  s += "# The Metal executor backend (--backend metal|auto) exists on Apple\n";
  s += "# hosts only: its Objective-C++ unit needs clang and the Metal +\n";
  s += "# Foundation frameworks, JIT-compiles its kernels at run time (no\n";
  s += "# Metal toolchain needed to build), and degrades to the CPU where no\n";
  s += "# device exists. Everywhere else — and under SEEML_NO_METAL=1 — the\n";
  s += "# stub takes its place and the package stays a plain C++ build, so a\n";
  s += "# Linux or Windows package is byte-for-byte what it was before.\n";
  s += "METAL_OBJ=metal_backend_stub.o\n";
  s += "METAL_LDFLAGS=\"\"\n";
  s += "# (-fobjc-arc needs a clang-family CXX; a GCC set via CXX takes the\n";
  s += "# stub, so the cross-toolchain promise holds on Darwin too.)\n";
  // The switch is tested as the tree's build.sh tests its own (CR3 #144
  // F23): empty, 0, off, false, no and n are OFF; anything else is ON.
  s += "seeml_on() {\n";
  s += "  case \"$(printf '%s' \"$1\" | tr '[:upper:]' '[:lower:]')\" in\n";
  s += "    \"\"|0|off|false|no|n) return 1 ;;\n";
  s += "    *) return 0 ;;\n";
  s += "  esac\n";
  s += "}\n";
  s +=
      "if [ \"$(uname -s)\" = \"Darwin\" ] && ! seeml_on \"${SEEML_NO_METAL:-}\" "
      "&& \"$CXX\" --version 2>/dev/null | grep -qi clang; then\n";
  s += "  $CXX $FLAGS -x objective-c++ -fobjc-arc -c "
       "runtime/executor/metal_backend.mm -o metal_backend.o\n";
  s += "  METAL_OBJ=metal_backend.o\n";
  s += "  METAL_LDFLAGS=\"-framework Metal -framework Foundation\"\n";
  s += "else\n";
  s += "  $CXX $FLAGS -c runtime/executor/metal_backend_stub.cc "
       "-o metal_backend_stub.o\n";
  s += "fi\n";
  // The profiler's energy meter (#202) reads IOReport through
  // CoreFoundation where the compiler targets Apple with clang, independent
  // of SEEML_NO_METAL; elsewhere it is a stub. The test is energy_meter.h's
  // own condition (__APPLE__ && __clang__) asked of the compiler itself, not
  // of the build host: a Linux host cross-compiling for Apple needs the
  // framework, and a Mac cross-compiling for Linux must not pass it.
  s += "ENERGY_LDFLAGS=\"\"\n";
  s +=
      "CXX_MACROS=$($CXX $FLAGS -dM -E -x c++ /dev/null 2>/dev/null || true)\n";
  s += "case \"$CXX_MACROS\" in\n";
  s += "  *\"#define __APPLE__ \"*)\n";
  s += "    case \"$CXX_MACROS\" in\n";
  s += "      *\"#define __clang__ \"*) "
       "ENERGY_LDFLAGS=\"-framework CoreFoundation\" ;;\n";
  s += "    esac ;;\n";
  s += "esac\n";
}

/// The link, and the clean-up after it.
void AppendLink(std::string& s) {
  s +=
      "$CXX $FLAGS update_main.o update_plan_embedded.o update_engine.o "
      "contract.o plan_loader.o gate.o runtime_screen.o dataset.o batch_pipeline.o gemm.o elementwise.o "
      "activation.o normalization.o loss.o optimizer.o attention.o "
      "backend.o cpu_backend.o $METAL_OBJ "
      "parallel_for.o durable_io.o plan_validator.o checkpoint.o "
      "byte_level_bpe.o text_ingest.o "
      "$METAL_LDFLAGS $ACCEL_LDFLAGS $ENERGY_LDFLAGS -o model_update\n";
  s +=
      "# The .o files are intermediates; the deliverable is the binary (and,\n";
  s += "# in the disk mode, the plan file beside it).\n";
  s += "rm -f ./*.o\n";
  s += "echo \"built: $(pwd)/model_update$PLAN_NOTE\"\n";
}

std::string BuildScript(bool relaxed_plan) {
  std::string s;
  s += "#!/bin/sh\n";
  s += "# Generated by seeml-update-compile: builds the self-contained\n";
  s += "# `model_update` executable from the vendored runtime sources.\n";
  s += "# Cross-compile by setting CXX to your target toolchain.\n";
  s += "set -e\n";
  s += "cd \"$(dirname \"$0\")\"\n";
  s += "CXX=\"${CXX:-c++}\"\n";
  if (relaxed_plan) AppendCertificateGate(s);
  AppendCompileFlags(s, relaxed_plan);
  AppendPlanUnit(s);
  AppendRuntimeUnits(s, relaxed_plan);
  AppendPlatformUnits(s);
  AppendLink(s);
  return s;
}

