#!/usr/bin/env python3
"""Generate source/tokenizer/unicode_tables.h from Python's unicodedata.

The byte-level BPE pre-tokenizer (source/tokenizer/, S2 #148) runs the
GPT-2 split pattern, whose classes are Unicode general categories: \\p{L}
(letters), \\p{N} (numbers) and \\s (White_Space). The core is dependency-
free, so the categories travel as sorted, non-overlapping code point
ranges in a committed header; this script is how the header is made, and
the Unicode version it was made from is stamped into it. Regenerate when
Python's unicodedata moves and the reference tokenizer follows:

    python3 tool/gen_unicode_tables.py > source/tokenizer/unicode_tables.h

Standard library only.
"""
import sys
import unicodedata

# The Unicode White_Space property (PropList.txt), stable since Unicode 6.
WHITE_SPACE = [(0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085),
               (0x00A0, 0x00A0), (0x1680, 0x1680), (0x2000, 0x200A),
               (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F),
               (0x3000, 0x3000)]


def ranges(major):
    out, start = [], None
    for cp in range(0x110000):
        if unicodedata.category(chr(cp)).startswith(major):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, table, what):
    print(f"// {what}: {len(table)} ranges, inclusive, sorted.")
    print(f"inline constexpr CodePointRange {name}[] = {{")
    line = "   "
    for lo, hi in table:
        cell = f" {{0x{lo:04X}, 0x{hi:04X}}},"
        if len(line) + len(cell) > 78:
            print(line)
            line = "   "
        line += cell
    print(line)
    print("};")
    print()


def main():
    out = sys.stdout
    print("// Generated by tool/gen_unicode_tables.py from Python's unicodedata",
          file=out)
    print(f"// (Unicode {unicodedata.unidata_version}). Do not edit by hand.",
          file=out)
    print("#ifndef SEEML_SOURCE_TOKENIZER_UNICODE_TABLES_H_")
    print("#define SEEML_SOURCE_TOKENIZER_UNICODE_TABLES_H_")
    print()
    print("#include <cstdint>")
    print()
    print("namespace seeml::tokenizer {")
    print()
    print(f'inline constexpr const char* kUnicodeVersion = '
          f'"{unicodedata.unidata_version}";')
    print()
    print("struct CodePointRange {")
    print("  uint32_t lo;")
    print("  uint32_t hi;")
    print("};")
    print()
    emit("kLetterRanges", ranges("L"), "General category L* (\\p{L})")
    emit("kNumberRanges", ranges("N"), "General category N* (\\p{N})")
    emit("kWhiteSpaceRanges", WHITE_SPACE, "White_Space (\\s)")
    print("}  // namespace seeml::tokenizer")
    print()
    print("#endif  // SEEML_SOURCE_TOKENIZER_UNICODE_TABLES_H_")


if __name__ == "__main__":
    main()
